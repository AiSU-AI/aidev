// itoa is a local int-to-string so the test file doesn't need strconv.
func itoa(n int) string {
	if n == 0 {
		return "0"
	}
	var buf [8]byte
	i := len(buf)
	for n > 0 {
		i--
		buf[i] = byte('0' + n%10)
		n /= 10
	}
	return strings.TrimSpace(string(buf[i:]))
}
