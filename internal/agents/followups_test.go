const sampleFollowUpsFile = `# Follow-up issues proposed by the Reviewer

_Generated by aidev on 2026-04-13. Review these, then file manually or wait for ` + "`aidev followups --file-issues`" + ` in a future release._

## 1. Refactor oldPkg/legacy.go

labels: tech-debt, refactor

200-line function the new code touches indirectly. Worth extracting to a package-private helper so the diff the Implementer produced doesn't accumulate more complexity.

---

## 2. Add integration test for the Foo flow

labels: testing

No existing coverage — the new code nearly touches it. Add a table-driven test against the Foo API boundary.

---

## 3. Document the FooConfig API

Public function with no godoc. Boy Scout violation right next to the new code.

---
`

func TestParseFollowUpsFileHappyPath(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "followups.md")
	if err := os.WriteFile(path, []byte(sampleFollowUpsFile), 0o644); err != nil {
		t.Fatal(err)
	}
	got, err := ParseFollowUpsFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if len(got) != 3 {
		t.Fatalf("got %d follow-ups, want 3 (%+v)", len(got), got)
	}
	want := []struct {
		title  string
		labels []string
	}{
		{"Refactor oldPkg/legacy.go", []string{"tech-debt", "refactor"}},
		{"Add integration test for the Foo flow", []string{"testing"}},
		{"Document the FooConfig API", nil},
	}
	for i, w := range want {
		if got[i].Title != w.title {
			t.Errorf("fu[%d].Title = %q, want %q", i, got[i].Title, w.title)
		}
		if len(got[i].Labels) != len(w.labels) {
			t.Errorf("fu[%d].Labels = %v, want %v", i, got[i].Labels, w.labels)
		} else {
			for j, l := range w.labels {
				if got[i].Labels[j] != l {
					t.Errorf("fu[%d].Labels[%d] = %q, want %q", i, j, got[i].Labels[j], l)
				}
			}
		}
		if got[i].Body == "" {
			t.Errorf("fu[%d].Body should not be empty", i)
		}
	}
}

