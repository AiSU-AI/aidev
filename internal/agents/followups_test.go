func TestParseFollowUpsFileSkipsPreamble(t *testing.T) {
	md := "# Some header\n\nSome intro paragraph.\n\n---\n\n## 1. The only proposal\n\nBody text here.\n\n---\n"
	dir := t.TempDir()
	path := filepath.Join(dir, "followups.md")
	os.WriteFile(path, []byte(md), 0o644)
	got, _ := ParseFollowUpsFile(path)
	if len(got) != 1 {
		t.Errorf("got %d, want 1 (preamble should be skipped)", len(got))
	}
	if got[0].Title != "The only proposal" {
		t.Errorf("title = %q", got[0].Title)
	}
}

func TestFileFollowUpsCallsFilerForEachProposal(t *testing.T) {
	proposals := []FollowUpIssue{
		{Title: "first", Body: "body1", Labels: []string{"a"}},
		{Title: "second", Body: "body2", Labels: []string{"b", "c"}},
	}
	calls := 0
	filer := func(title, body string, labels []string) (int, string, error) {
		calls++
		return 100 + calls, "https://github.com/o/r/issues/" + itoa(100+calls), nil
	}
	filed, err := FileFollowUps(proposals, filer)
	if err != nil {
		t.Fatal(err)
	}
	if calls != 2 {
		t.Errorf("calls = %d, want 2", calls)
	}
	if len(filed) != 2 {
		t.Errorf("filed = %d, want 2", len(filed))
	}
	if filed[0].Number != 101 || filed[1].Number != 102 {
		t.Errorf("numbers = %d/%d", filed[0].Number, filed[1].Number)
	}
}

func TestFileFollowUpsStopsOnFirstError(t *testing.T) {
	proposals := []FollowUpIssue{
		{Title: "first"},
		{Title: "second"},
		{Title: "third"},
	}
	calls := 0
	filer := func(title, body string, labels []string) (int, string, error) {
		calls++
		if calls == 2 {
			return 0, "", errors.New("rate limit")
		}
		return calls, "url", nil
	}
	filed, err := FileFollowUps(proposals, filer)
	if err == nil {
		t.Error("expected error")
	}
	if calls != 2 {
		t.Errorf("should stop at 2 calls, got %d", calls)
	}
	// The first proposal should still be in the filed slice.
	if len(filed) != 1 {
		t.Errorf("filed = %d, want 1 (the one that succeeded before the error)", len(filed))
	}
}

